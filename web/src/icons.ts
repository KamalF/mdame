const parsed = new Map<string, SVGSVGElement>();

/** A clone costs a third of a parse: a filter or a page with many code
 * blocks asks for thousands of icons. */
export function icon(name: string): SVGSVGElement {
  let svg = parsed.get(name);
  if (!svg) {
    svg = document.createElementNS("http://www.w3.org/2000/svg", "svg");
    for (const [key, value] of Object.entries({
      viewBox: "0 0 24 24",
      fill: "none",
      stroke: "currentColor",
      "stroke-width": "1.75",
      "stroke-linecap": "round",
      "stroke-linejoin": "round",
      "aria-hidden": "true",
      class: "mdame-icon",
    })) {
      svg.setAttribute(key, value);
    }
    svg.innerHTML = ICONS[name];
    parsed.set(name, svg);
  }
  return svg.cloneNode(true) as SVGSVGElement;
}

export function iconButton(
  label: string,
  name: string,
  onClick: () => void,
  title = label,
): HTMLButtonElement {
  const button = document.createElement("button");
  button.className = "mdame-icon-button";
  button.setAttribute("aria-label", label);
  button.title = title;
  button.append(icon(name));
  button.addEventListener("click", onClick);
  return button;
}

/** The icon name for a file, from the family that /api/tree sends. */
export function fileIcon(family: string | undefined): string {
  if (family === "markdown") return "text";
  // `undefined in ICONS` is false, so a missing family gives "file".
  return (family as string) in ICONS ? (family as string) : "file";
}
